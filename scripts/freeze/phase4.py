def norm(runs):
    out = []
    for r in runs:
        r = dict(r)
        r["text"] = re.sub(r"\n\n+", "\n", r["text"])
        if out and out[-1]["text"].endswith("\n") and r["text"].startswith("\n"):
            r["text"] = r["text"][1:]
        out.append(r)
    return out

def txt(b): return "".join(r["text"] for r in b["runs"])
def R(b): return norm(b["runs"])
def plain(s, **kw): return [dict(text=s, **kw)]

