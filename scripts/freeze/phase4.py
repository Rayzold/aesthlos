def flow(blocks, patch=None):
    out = []
    for i, b in enumerate(blocks):
        if patch and i in patch:
            out.extend(patch[i]); continue
        t = b["type"]
        if t == "text":
            o = {"type": "text", "tag": b["tag"], "runs": R(b)}
            if b.get("color"): o["color"] = b["color"]
            out.append(o)
        elif t == "link":
            out.append({"type": "pdf", "text": b["text"], "href": b["href"]})
        elif t == "image":
            out.append({"type": "image", "src": b["src"], "alt": b["alt"]})
    return out

